export function isLocale(segment: string | undefined | null): segment is LangCode {
  return !!segment && (SUPPORTED_LOCALES as string[]).includes(segment);
}

export function resolveLocale(segment: string | undefined | null): LangCode {
  return isLocale(segment) ? segment : DEFAULT_LOCALE;
}

/** `/en` + `/services/tourist` -> `/en/services/tourist` (no trailing slash). */
export function localePath(locale: string, path = "/"): string {
  const clean = path === "/" || path === "" ? "" : `/${path.replace(/^\/+/, "").replace(/\/+$/, "")}`;
  return `/${locale}${clean}`;
}

/** Absolute canonical-style URL for a locale + path pair. */
export function absoluteUrl(locale: string, path = "/"): string {
  return `${SITE_ORIGIN}${localePath(locale, path)}`;
}

/**
 * The language-neutral form of a page: proxy.ts negotiates a locale for any
 * locale-less path, so this is the x-default target of that very page rather than
 * of the home page. A query string is kept (/Blogs?page=2).
 */
export function localeLessUrl(path = "/"): string {
  if (!path || path === "/") return `${SITE_ORIGIN}/`;
  return `${SITE_ORIGIN}${path.startsWith("/") ? path : `/${path}`}`;
}
